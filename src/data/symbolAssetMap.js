// Get the static require source for a hexcode
export function getOpenMojiSource(hexcode) {
  return openmojiAssets[hexcode] || null;
}

// Get OpenMoji source for a word
export function getOpenMojiForWord(word) {
  const hex = wordToHexcode[word.toLowerCase()];
  if (!hex) return null;
  return openmojiAssets[hex] || null;
}
